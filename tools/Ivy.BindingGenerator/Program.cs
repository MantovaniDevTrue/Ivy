using System.Text;
using System.Text.Json;
using Ivy.BindingGenerator;

if (args.Length < 2)
{
    Console.Error.WriteLine("Uso: Ivy.BindingGenerator <diretório DummyDll> <saída> [prefixos separados por vírgula] [arquivo-SDK-MainPlayer.cs]");
    return 2;
}
var prefixes = (args.Length > 2 ? args[2] : "Terraria,Microsoft.Xna.Framework,ReLogic").Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
var catalog = CatalogReader.ReadDirectory(args[0], prefixes);
Directory.CreateDirectory(args[1]);
if (args.Length > 3)
    File.WriteAllText(args[3], GameplaySdkGenerator.Generate(catalog));
if (args.Length > 4)
{
    var typed = TypedAccessGenerator.Generate(catalog);
    File.WriteAllText(args[4], typed.Source);
    File.WriteAllText(Path.Combine(args[1], "typed-access.json"), JsonSerializer.Serialize(new {
        profile = TypedAccessGenerator.Profile, typed.Types, typed.Fields, typed.Methods, typed.Properties, typed.Omitted, typed.Families,
        runtimeValidation = "resolved lazily by full signature; Android acceptance pending"
    }, new JsonSerializerOptions { WriteIndented = true }) + "\n");
}
var json = new JsonSerializerOptions { WriteIndented = true, PropertyNamingPolicy = JsonNamingPolicy.CamelCase };
File.WriteAllText(Path.Combine(args[1], "native-api.json"), JsonSerializer.Serialize(catalog, json) + "\n");
var types = catalog.Assemblies.SelectMany(a => a.Types).ToArray();
var methods = types.SelectMany(t => t.Methods).ToArray();
var report = new
{
    schemaVersion = 1, mode = catalog.Mode, prefixes,
    assemblies = catalog.Assemblies.Length, types = types.Length, methods = methods.Length,
    fields = types.Sum(t => t.Fields.Length), properties = types.Sum(t => t.Properties.Length), events = types.Sum(t => t.Events.Length),
    primitiveOnlySignatures = methods.Count(m => m.ReviewReasons.Length == 0),
    reviewReasons = methods.SelectMany(m => m.ReviewReasons).GroupBy(s => s).OrderBy(g => g.Key).ToDictionary(g => g.Key, g => g.Count()),
    runtimeMethodsValidated = 0, hooksInstalled = 0,
    status = "Descriptors generated; native invocation, public facades and hook ABI validation remain separate stages."
};
File.WriteAllText(Path.Combine(args[1], "summary.json"), JsonSerializer.Serialize(report, json) + "\n");

var source = new StringBuilder("// <auto-generated/>\nnamespace Ivy.Generated;\n\npublic sealed record NativeMethodDescriptor(string Id, string Assembly, string DeclaringType, string Name, string ReturnType, string[] ParameterTypes, bool IsStatic, int GenericArity);\n\n");
foreach (var type in types)
{
    var className = "Type_" + Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(Encoding.UTF8.GetBytes(type.Assembly + "|" + type.Name)))[..16];
    source.Append("public static class ").Append(className).Append("\n{\n    public const string NativeType = ").Append(Quote(type.Name)).Append(";\n");
    foreach (var method in type.Methods)
    {
        var label = new string(method.Name.Select(c => char.IsAsciiLetterOrDigit(c) || c == '_' ? c : '_').ToArray());
        source.Append("    public static readonly NativeMethodDescriptor M_").Append(label).Append('_').Append(method.Token.ToString("X8")).Append(" = new(")
            .Append(Quote(method.Id)).Append(", ").Append(Quote(method.Assembly)).Append(", ").Append(Quote(method.DeclaringType)).Append(", ")
            .Append(Quote(method.Name)).Append(", ").Append(Quote(method.ReturnType)).Append(", new string[] { ")
            .Append(string.Join(", ", method.Parameters.Select(p => Quote(p.Type)))).Append(" }, ")
            .Append(method.IsStatic ? "true" : "false").Append(", ").Append(method.GenericArity).Append(");\n");
    }
    foreach (var method in type.Methods.Where(m => m.ReviewReasons.Length == 0))
    {
        var label = new string(method.Name.Select(c => char.IsAsciiLetterOrDigit(c) || c == '_' ? c : '_').ToArray()) + "_" + method.Token.ToString("X8");
        var parameters = new List<string>();
        if (!method.IsStatic) parameters.Add("global::System.IntPtr instance");
        parameters.AddRange(method.Parameters.Select((p, index) => AbiType(p.Type) + " arg" + index));
        parameters.Add("global::System.IntPtr methodInfo");
        source.Append("    [global::System.Runtime.InteropServices.UnmanagedFunctionPointer(global::System.Runtime.InteropServices.CallingConvention.Cdecl)]\n")
            .Append("    public delegate ").Append(AbiType(method.ReturnType)).Append(" D_").Append(label).Append('(').Append(string.Join(", ", parameters)).Append(");\n");
    }
    source.Append("}\n\n");
}
File.WriteAllText(Path.Combine(args[1], "NativeMethodDescriptors.g.cs"), source.ToString());
File.WriteAllText(Path.Combine(args[1], "Ivy.Generated.csproj"), "<Project Sdk=\"Microsoft.NET.Sdk\"><PropertyGroup><TargetFramework>net10.0</TargetFramework><Nullable>enable</Nullable></PropertyGroup></Project>\n");
Console.WriteLine(JsonSerializer.Serialize(report, json));
return 0;

static string Quote(string value) => JsonSerializer.Serialize(value);

static string AbiType(string type) => type switch
{
    "System.Void" => "void", "System.Boolean" => "byte", "System.Char" => "ushort",
    _ => "global::" + type
};
